#!/usr/bin/env bash
# =============================================================
#  System report script
#  Author:  Kanagat Beken
#  Project: kanagat-beken-student-api
#  Works on macOS and Linux. Output -> logs/Kanagat_Beken_system_report.log
# =============================================================

STUDENT_NAME="Kanagat Beken"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
LOG_DIR="$PROJECT_DIR/logs"
LOG_FILE="$LOG_DIR/Kanagat_Beken_system_report.log"
OS_TYPE="$(uname -s)"

mkdir -p "$LOG_DIR"

section() {
    printf '\n===== %s =====\n' "$1"
}

generate_report() {
    echo "################################################################"
    echo "  SYSTEM REPORT - $STUDENT_NAME"
    echo "################################################################"

    section "Student"
    echo "Full name: $STUDENT_NAME"

    section "Date and time"
    date '+%Y-%m-%d %H:%M:%S %Z'

    section "Current user"
    echo "Username: $(whoami)"
    echo "Hostname: $(hostname)"

    section "Operating system and kernel"
    if [ "$OS_TYPE" = "Darwin" ]; then
        echo "OS:      $(sw_vers -productName) $(sw_vers -productVersion) (build $(sw_vers -buildVersion))"
    elif [ -f /etc/os-release ]; then
        echo "OS:      $(grep '^PRETTY_NAME=' /etc/os-release | cut -d= -f2 | tr -d '"')"
    else
        echo "OS:      $OS_TYPE"
    fi
    echo "Kernel:  $(uname -sr)"
    echo "Arch:    $(uname -m)"

    section "CPU"
    if [ "$OS_TYPE" = "Darwin" ]; then
        echo "Model:   $(sysctl -n machdep.cpu.brand_string)"
        echo "Cores:   $(sysctl -n hw.ncpu)"
    else
        lscpu | grep -E '^(Model name|CPU\(s\)|Architecture|Thread\(s\) per core)'
    fi

    section "Memory"
    if [ "$OS_TYPE" = "Darwin" ]; then
        total_mb=$(( $(sysctl -n hw.memsize) / 1024 / 1024 ))
        echo "Total memory: ${total_mb} MB"
        top -l 1 -n 0 | grep PhysMem
    else
        free -h
    fi

    section "Disk usage"
    df -h

    section "Available disk space (project disk)"
    df -h "$PROJECT_DIR" | awk 'NR==2 {print "Mount: " $NF "  Size: " $2 "  Available: " $4 "  Used: " $5}'

    echo
    echo "Report generated by $STUDENT_NAME at $(date '+%Y-%m-%d %H:%M:%S')"
    echo "================================================================"
}

# print to the terminal AND append to the personal log file
generate_report | tee -a "$LOG_FILE"

echo
echo "Saved to: $LOG_FILE"
